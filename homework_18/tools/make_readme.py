def table(headers, rows, widths):
    """Проста ASCII-таблиця з переносом довгого тексту в комірках."""
    def border(left, mid, right, fill="-"):
        return left + mid.join(fill * (w + 2) for w in widths) + right

    def line(cells):
        wrapped = [textwrap.wrap(c, widths[i]) or [""] for i, c in enumerate(cells)]
        height = max(len(w) for w in wrapped)
        out = []
        for r in range(height):
            parts = []
            for i, col in enumerate(wrapped):
                text = col[r] if r < len(col) else ""
                parts.append(" " + text.ljust(widths[i]) + " ")
            out.append("|" + "|".join(parts) + "|")
        return "\n".join(out)

    res = [border("+", "+", "+"), line(headers), border("+", "+", "+", "=")]
    for i, row in enumerate(rows):
        res.append(line(row))
        res.append(border("+", "+", "+"))
    return "\n".join(res)


