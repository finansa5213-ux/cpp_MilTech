#ifndef UPLOAD_TYPES_H
#define UPLOAD_TYPES_H

#include <string>

namespace dz15 {

// ------------------------------------------------------------
// Підсумковий статус обробки одного теста.
//
// Класифікація визначає поведінку клієнта (див. п.3 і п.4 ТЗ):
//   Success / Overwritten — 2xx, робота з тестом завершена;
//   Rejected              — 400/401, ПОВТОРЮВАТИ ЗАБОРОНЕНО:
//                           той самий запит не стане кращим;
//   Exhausted             — 503/таймаут вичерпали ліміт спроб;
//   Missing               — локального файла немає (ТЗ дозволяє:
//                           «надсилаєте ті, що є»);
//   BadLocalFile          — файл є, але це не валідний JSON;
//   NotConfirmed          — POST успішний, але контрольний GET
//                           не підтвердив наявність на сервері.
// ------------------------------------------------------------
enum class UploadStatus {
    Success,
    Overwritten,
    Rejected,
    Exhausted,
    Missing,
    BadLocalFile,
    NotConfirmed
};

// ------------------------------------------------------------
// Рішення про подальші дії після однієї спроби POST.
// Виноситься окремим типом, щоб логіка «повторювати чи ні»
// була явною і тестованою, а не схованою в ланцюжку if-ів.
// ------------------------------------------------------------
enum class RetryDecision {
    Done,   // 2xx — успіх, більше не повторюємо
    Stop,   // 400/401 — фатально для цього теста, повтор безглуздий
    Again   // 503 або таймаут — має сенс спробувати ще раз
};

// ------------------------------------------------------------
// Рядок підсумкового звіту: тест → статус → кількість спроб.
// ------------------------------------------------------------
struct TestReport {
    std::string testId;                                  // "T01" … "T10"
    UploadStatus status = UploadStatus::Missing;
    int attempts = 0;                                    // фактично зроблено спроб
    int lastHttpCode = 0;                                // 0 — відповіді не було (таймаут)
    bool verifiedByGet = false;                          // контрольний GET дав found:true
    std::string detail;                                  // тіло помилки / пояснення
};

// Людиночитний підпис статусу для друку у звіті.
const char* toString(UploadStatus status);

// Чи вважається тест успішно зданим (для підсумкової статистики).
bool isSuccessful(UploadStatus status);

}  // namespace dz15

#endif  // UPLOAD_TYPES_H
