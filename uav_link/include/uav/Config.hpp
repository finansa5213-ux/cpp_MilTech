// Параметри маршрутизатора. Виміряні константи лежать у текстовому файлі,
// а не в коді: під час налагодження стенда їх міняють десятки разів, і
// перекомпіляція на кожну зміну порога - марна витрата часу.
#pragma once

#include <cstddef>
#include <cstdint>
#include <string>
#include <vector>

namespace uav {

struct Config {
    // --- пристрої ------------------------------------------------------
    std::string fcDevice    = "/dev/ttyAMA0";
    int         fcBaud      = 921600;
    std::string radioDevice = "/dev/uav_radio";
    int         radioBaud   = 57600;

    // --- мережа --------------------------------------------------------
    std::uint16_t udpPort     = 14550;
    std::string   peerHost    = "10.8.0.1";   ///< концентратор
    std::uint16_t peerPort    = 14550;
    std::uint16_t echoPort    = 14555;        ///< відбивач RTT на сервері
    std::uint16_t controlPort = 14552;
    std::string   operatorHost = "10.8.0.3";  ///< для вимірювання повного шляху
    std::vector<std::string> controlAllow = {"127.0.0.1", "10.8.0.3"};
    /// Приймати висхідний трафік лише від концентратора. Інакше розмежування
    /// прав обходиться прямою лінією зі станції на борт - перевірено 18.09.
    bool peerFixed = true;

    // --- часи й пороги (розділ 4) --------------------------------------
    double tLostSec        = 3.0;    ///< три пропущені HEARTBEAT наземної станції
    double tBackSec        = 10.0;
    double rttSwitchFullMs = 200.0;  ///< точка рівноваги 160,9 мс + 25 % запасу
    double rttBackFullMs   = 170.0;
    double rttOffsetMs     = 68.0;   ///< запасна оцінка ділянки сервер <-> оператор
    double rttStaleSec     = 5.0;
    double failsafeSec     = 5.0;
    std::string failsafeAction = "log";   ///< log | rtl
    /// Не командувати повернення, поки оцінювач не має дійсної абсолютної
    /// горизонтальної координати (ESTIMATOR_STATUS, біт POS_HORIZ_ABS).
    bool   requireNavForRtl = true;
    /// Виміри стану оцінювача, старші за це, недійсні.
    ///
    /// Значення здобуте вимірюванням, а не вибране. PX4 у режимі Normal
    /// призначає ESTIMATOR_STATUS частоту 0,50 Гц, але масштабує ВСІ потоки
    /// під MAV_1_RATE: на стенді 20.09.2026 коефіцієнт дорівнював 0,596, і
    /// фактична частота становила 0,298 Гц, тобто період 3,36 с. Строк
    /// придатності має покривати щонайменше три періоди - звідси 12 с.
    /// Початкові 5 с покривали лише півтора періоду, і одного пропущеного
    /// повідомлення вистачило б, щоб маршрутизатор вважав навігацію
    /// непридатною без жодної на те підстави.
    ///
    /// Якщо контролер цього повідомлення не передає взагалі, навігація
    /// вважається непридатною, і рівень 3 не спрацьовує - захист
    /// вироджується до власного NAV_DLL_ACT контролера, а не зникає.
    double navStaleSec      = 12.0;

    // --- потоки даних ---------------------------------------------------
    double      flushSec     = 0.02;  ///< накопичення телеметрії (закон розміру датаграми)
    std::size_t maxDatagram  = 1024;
    std::size_t maxBacklog   = 4096;  ///< застаріла телеметрія гірша за її відсутність
    double      keepaliveSec = 1.0;   ///< HEARTBEAT у резервний канал
    double      probeSec     = 1.0;
    double      fullProbeSec = 5.0;
    double      reportSec    = 30.0;

    /// Прочитати файл виду `ключ = значення`, `#` - коментар.
    /// Повертає false і заповнює err, якщо файл нечитний або ключ невідомий.
    static bool load(const std::string& path, Config& out, std::string& err);

    bool commandRtl() const { return failsafeAction == "rtl"; }
};

} // namespace uav
